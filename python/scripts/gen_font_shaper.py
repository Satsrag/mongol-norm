#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Build the bundled shaping font and its glyph table for the crate's `font` feature.

The font backend (`mongol_norm::FontShaper`, Cargo feature `font`) shapes with HarfBuzz rules
instead of the ported ones: harfrust runs the Hudum font mongfontbuilder composes, and the
crate reads the written units off the glyphs the font chose. Nothing of mongfontbuilder ships:
only the font, stripped of its outlines, and a table that names the written units of each glyph.

What this script maintains, all committed:

  fonts/mongfontbuilder.json      the pin: the upstream repository and commit the font was
                                  built from, and the checksums of what was built
  fonts/hudum.otf                 the stripped font (GSUB/GDEF/cmap and the sfnt skeleton)
  fonts/hudum.glyphs.txt          its glyph order — the glyph → written-unit mapping is read
                                  off these names (see _font_glyphs.py)
  src/generated/font_hudum.rs     that mapping as a static Rust table, by glyph id
  tests/data/mongfontbuilder/     the upstream Hudum conformance suites (core-hudum.tsv,
                                  eac-hudum.tsv), as of that commit

Building needs `git`, `uv` and network access (the checkout's own environment supplies
fontTools and mongfontbuilder); it clones the pinned commit into a temporary directory:

    python3 python/scripts/gen_font_shaper.py                   # rebuild from the pinned commit
    python3 python/scripts/gen_font_shaper.py --commit SHA      # move the pin to SHA, rebuild
    python3 python/scripts/gen_font_shaper.py --source DIR      # build from an existing checkout
    python3 python/scripts/gen_font_shaper.py --check           # exit 1 if a committed file is stale

`--check` needs nothing but Python: it re-renders the Rust table from the committed glyph
order and compares the font against the pin's checksum and glyph count. Both modes require
every written unit the font shows to be one of the rule data's (`python/mongol_norm/data/
MNG.json`): a font that brings a new unit is a change of the crate's unit vocabulary, which
is decided there, not here.

Python 3.9+, standard library only (the fontTools half is `_font_dump.py`).
"""
import argparse
import hashlib
import json
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

import _font_glyphs

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "fonts"
PIN = FONTS / "mongfontbuilder.json"
FONT = FONTS / "hudum.otf"
GLYPHS = FONTS / "hudum.glyphs.txt"
TABLE = ROOT / "src" / "generated" / "font_hudum.rs"
SUITES = ROOT / "tests" / "data" / "mongfontbuilder"
SUITE_NAMES = ("core-hudum.tsv", "eac-hudum.tsv")
RULES = ROOT / "python" / "mongol_norm" / "data" / "MNG.json"
DUMP = Path(__file__).resolve().with_name("_font_dump.py")

HEADER = "// @generated by python/scripts/gen_font_shaper.py -- DO NOT EDIT.\n"
COMMIT = re.compile(r"^[0-9a-f]{40}$")
STRUCTURAL_UNITS = ("Mvs", "Nirugu", "Zwj")


def die(message):
    raise SystemExit("gen_font_shaper: " + message)


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_pin():
    try:
        return json.loads(PIN.read_text(encoding="utf-8"))
    except FileNotFoundError:
        die("missing {}".format(PIN.relative_to(ROOT)))


def num_glyphs(path):
    """`maxp.numGlyphs` of an OpenType font, from the table directory alone."""
    blob = path.read_bytes()
    count = struct.unpack(">H", blob[4:6])[0]
    for index in range(count):
        tag, _, offset, _ = struct.unpack(">4sIII", blob[12 + 16 * index : 28 + 16 * index])
        if tag == b"maxp":
            return struct.unpack(">H", blob[offset + 4 : offset + 6])[0]
    die("{}: no maxp table".format(path.relative_to(ROOT)))


def rule_units():
    """The written units of the rule data, plus the structural ones."""
    doc = json.loads(RULES.read_text(encoding="utf-8"))
    units = set(STRUCTURAL_UNITS)
    for letter in doc["letters"]:
        for variant in letter["variants"]:
            units.update(variant["written"])
    return units


def check_units(names):
    unknown = sorted(_font_glyphs.font_units(names) - rule_units())
    if unknown:
        die("the font shows written units the rule data does not have: {}".format(", ".join(unknown)))


# ── the Rust table ─────────────────────────────────────────────────────

def position(name):
    return "Position::" + name.capitalize()


def render_table(names, pin):
    glyphs = []
    counts = {kind: 0 for kind in _font_glyphs.KINDS}
    for name in names:
        try:
            glyph = _font_glyphs.classify(name)
        except ValueError as error:
            die(str(error))
        counts[glyph.kind] += 1
        if glyph.kind == "letters":
            units = ", ".join("WrittenUnit::" + unit for unit in glyph.units)
            expr = "Glyph::letters(&[{}], {}, {}, {})".format(
                units, glyph.letters, position(glyph.form), position(glyph.joining)
            )
        else:
            expr = "Glyph::{}()".format(glyph.kind)
        glyphs.append((expr, name))
    out = [HEADER]
    out.append("// Source: fonts/hudum.glyphs.txt (sha256 {})\n".format(sha256(GLYPHS)[:16]))
    out.append("// Font:   fonts/hudum.otf, built by mongfontbuilder {} at {} {}\n".format(
        pin["mongfontbuilder_version"], pin["repository"], pin["commit"][:12]))
    out.append("//\n// The glyph -> written-unit table of the bundled shaping font, by glyph id: "
               "{} glyphs,\n// {} letter variants/ligatures, {} controls, {} silent, "
               "{} unsupported.\n\n".format(
                   len(names), counts["letters"],
                   counts["mvs"] + counts["nirugu"] + counts["zwj"],
                   counts["silent"], counts["unsupported"]))
    out.append("use crate::font::Glyph;\n")
    out.append("use crate::generated::enums::WrittenUnit;\n")
    out.append("use crate::tables::Position;\n\n")
    out.append("/// The number of glyphs in `fonts/hudum.otf`.\n")
    out.append("pub(crate) const GLYPH_COUNT: usize = {};\n\n".format(len(names)))
    out.append("/// What each glyph of `fonts/hudum.otf` shows, indexed by glyph id.\n")
    out.append("#[rustfmt::skip]\n")
    out.append("pub(crate) static GLYPHS: [Glyph; GLYPH_COUNT] = [\n")
    for index, (expr, name) in enumerate(glyphs):
        out.append("    {}, // {} {}\n".format(expr, index, name))
    out.append("];\n")
    return "".join(out)


# ── building ───────────────────────────────────────────────────────────

def run(args, cwd, capture=False):
    print("+ " + " ".join(str(arg) for arg in args), flush=True)
    result = subprocess.run(args, cwd=str(cwd), check=False, text=True,
                            stdout=subprocess.PIPE if capture else None)
    if result.returncode != 0:
        die("command failed ({}): {}".format(result.returncode, " ".join(str(a) for a in args)))
    return result.stdout


def checkout(pin, source, commit, workdir):
    """A checkout of the upstream repository to build from, with its HEAD and commit date.

    Without `--source` the pinned repository is cloned and `commit` (default: the pinned one)
    checked out. With `--source` the checkout is built as it stands — its HEAD becomes the
    pin — unless `--commit` asks for a specific commit; either way it must be clean, so that
    the pin names exactly what was built.
    """
    if source is None:
        source = workdir / "mongolian"
        run(["git", "clone", "--quiet", pin["repository"], str(source)], workdir)
        run(["git", "-C", str(source), "checkout", "--quiet", commit or pin["commit"]], workdir)
    else:
        source = Path(source).resolve()
        if not (source / "mongfontbuilder" / "tests" / "build.py").is_file():
            die("{} is not a Kushim-Jiang/mongolian checkout".format(source))
        if commit is not None:
            run(["git", "-C", str(source), "checkout", "--quiet", commit], workdir)
    git = ["git", "-C", str(source)]
    head = run(git + ["rev-parse", "HEAD"], workdir, capture=True).strip()
    date = run(git + ["show", "-s", "--format=%cI", "HEAD"], workdir, capture=True).strip()
    if not COMMIT.match(head):
        die("unexpected HEAD {!r}".format(head))
    if commit is not None and head != commit:
        die("checked out {} but HEAD is {}".format(commit, head))
    if run(git + ["status", "--porcelain", "--untracked-files=no"], workdir, capture=True).strip():
        die("{} has uncommitted changes; the pin must name exactly what was built".format(source))
    return source, head, date


def build(source, commit):
    pin = load_pin()
    with tempfile.TemporaryDirectory(prefix="mongol-norm-font-") as temp:
        workdir = Path(temp)
        source, head, date = checkout(pin, source, commit, workdir)
        package = source / "mongfontbuilder"
        run(["uv", "run", "--quiet", "python", "tests/build.py", "--only", "hudum"], package)
        built = package / "temp" / "hudum.otf"
        if not built.is_file():
            die("the build produced no {}".format(built))
        out = workdir / "out"
        meta = json.loads(run(["uv", "run", "--quiet", "python", str(DUMP), str(built), str(out)],
                              package, capture=True))
        names = _font_glyphs.read_glyph_order(out / "hudum.glyphs.txt")
        check_units(names)

        FONTS.mkdir(exist_ok=True)
        shutil.copyfile(out / "hudum.otf", FONT)
        shutil.copyfile(out / "hudum.glyphs.txt", GLYPHS)
        SUITES.mkdir(parents=True, exist_ok=True)
        for name in SUITE_NAMES:
            suite = package / "src" / "mongfontbuilder" / "testSuites" / name
            if not suite.is_file():
                die("the checkout has no suite {}".format(suite))
            shutil.copyfile(suite, SUITES / name)

    pin = {
        "repository": pin["repository"],
        "commit": head,
        "committed": date,
        "mongfontbuilder_version": meta["mongfontbuilder_version"],
        "build": "cd mongfontbuilder && uv run python tests/build.py --only hudum",
        "source": {
            "path": "mongfontbuilder/temp/hudum.otf",
            "sha256": meta["source_sha256"],
            "bytes": meta["source_bytes"],
        },
        "font": {
            "path": "fonts/hudum.otf",
            "sha256": meta["font_sha256"],
            "bytes": meta["font_bytes"],
            "glyphs": meta["glyphs"],
        },
        "suites": list(SUITE_NAMES),
    }
    PIN.write_text(json.dumps(pin, indent=2) + "\n", encoding="utf-8")
    TABLE.write_text(render_table(names, pin), encoding="utf-8")
    for path in (PIN, FONT, GLYPHS, TABLE) + tuple(SUITES / name for name in SUITE_NAMES):
        print("wrote", path.relative_to(ROOT).as_posix())
    return 0


def check():
    pin = load_pin()
    problems = []
    for path in (FONT, GLYPHS, TABLE) + tuple(SUITES / name for name in pin["suites"]):
        if not path.is_file():
            problems.append("missing: " + path.relative_to(ROOT).as_posix())
    if problems:
        print("\n".join(problems))
        return 1
    if sha256(FONT) != pin["font"]["sha256"]:
        problems.append("fonts/hudum.otf does not match the pin's checksum")
    names = _font_glyphs.read_glyph_order(GLYPHS)
    check_units(names)
    if len(names) != pin["font"]["glyphs"]:
        problems.append("fonts/hudum.glyphs.txt has {} names, the pin says {}".format(
            len(names), pin["font"]["glyphs"]))
    if num_glyphs(FONT) != len(names):
        problems.append("fonts/hudum.otf has {} glyphs, fonts/hudum.glyphs.txt names {}".format(
            num_glyphs(FONT), len(names)))
    if TABLE.read_text(encoding="utf-8") != render_table(names, pin):
        problems.append("stale:   " + TABLE.relative_to(ROOT).as_posix())
    if problems:
        print("\n".join(problems))
        print("run: python3 python/scripts/gen_font_shaper.py")
        return 1
    print("the bundled shaping font and its glyph table are fresh ({} glyphs, mongfontbuilder {})".format(
        len(names), pin["commit"][:12]))
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="verify that the committed font, glyph table and suites are up to date")
    parser.add_argument("--source", metavar="DIR",
                        help="build from this Kushim-Jiang/mongolian checkout instead of cloning")
    parser.add_argument("--commit", metavar="SHA",
                        help="move the pin to this upstream commit (full 40-hex SHA) and build it")
    args = parser.parse_args()
    if args.check:
        if args.source or args.commit:
            parser.error("--check takes no --source/--commit")
        return check()
    if args.commit is not None and not COMMIT.match(args.commit):
        parser.error("--commit wants a full 40-character SHA")
    return build(args.source, args.commit)


if __name__ == "__main__":
    sys.exit(main())
